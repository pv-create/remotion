import type {MeterSpec, StickerSpec} from '../motion/types';

/**
 * Схема перебивки — партиции топика и консьюмеры на них.
 * Состояние задаётся шагами: что показано и в каком кадре это изменилось.
 * Дорожки и консьюмеры только добавляются, обратно не убираются.
 */
export interface CutStep {
  /** кадр от начала перебивки */
  at: number;
  /** сколько партиций показано */
  open: number;
  /** сообщений в очереди: одно число на все дорожки или по числу на каждую */
  cells: number | number[];
  /** сколько партиций читает свой консьюмер */
  consumers: number;
  /** консьюмеры, которым партиции не досталось, — стоят и ничего не делают */
  idle?: number;
  /** за сколько кадров меняется заполнение очередей. По умолчанию dur.block */
  over?: number;
}

/**
 * Схема перебивки — пулы потоков вызывающего сервиса и ресурсы, в которые
 * они ходят. Один пул = одна строка: слоты потоков, стрелка, ресурс.
 * Как и у дорожек, состояние только нарастает: пулы открываются, потоки
 * застревают, ресурсы зависают — обратно ничего не откатывается.
 */
export interface PoolStep {
  /** кадр от начала перебивки */
  at: number;
  /** сколько пулов показано */
  open: number;
  /** застрявших потоков в каждом пуле: ждут ответа, который не придёт */
  stuck: number[];
  /** работающих потоков в каждом пуле (accent, «происходит сейчас») */
  busy?: number[];
  /** индексы ресурсов, которые не отвечают */
  hung?: number[];
  /** вызывающий сервис лёг: свободных потоков не осталось */
  dead?: boolean;
  /** за сколько кадров застревают потоки этого шага. По умолчанию dur.block */
  over?: number;
}

export interface PoolsSpec {
  /** подпись вызывающего сервиса на рамке */
  caller: string;
  pools: {
    /** потоков в пуле; 4 в общем пуле читаются, 6 — уже нет */
    size: number;
    /** ресурс, в который ходит пул */
    target: string;
  }[];
  steps: PoolStep[];
}

/**
 * Схема перебивки — поток сообщений по ярусам сверху вниз: producer →
 * exchange → очереди (RabbitMQ) или producer → топик с партициями → группы
 * консьюмеров (Kafka). Стрелки идут от каждого узла яруса к каждому узлу
 * следующего; у яруса с рамкой стрелки упираются в рамку. Узлы только
 * открываются, обратно не закрываются.
 */
export interface FlowTier {
  /** рамка вокруг узлов яруса (TOPIC вокруг партиций) */
  frame?: string;
  nodes: string[];
  /** узлы яруса — очереди: показывают ячейки сообщений */
  queue?: boolean;
  /** сколько сообщений уже лежит в каждой очереди на старте */
  cells?: number[];
}

export interface FlowStep {
  /** кадр от начала перебивки */
  at: number;
  /** открытых узлов в каждом ярусе */
  open: number[];
  /** узлы последнего яруса, которые читают: стрелка в них ink, узел залит */
  reading?: number[];
}

export interface FlowPacket {
  /** кадр, когда сообщение выходит из узла первого яруса */
  at: number;
  /** индекс узла на каждом ярусе пути; в очереди сообщение остаётся ячейкой */
  route: number[];
  /** сколько кадров стоит в промежуточном узле. По умолчанию dwell перебивки */
  dwell?: number;
}

export interface FlowSpec {
  tiers: FlowTier[];
  steps: FlowStep[];
  packets: FlowPacket[];
  /** сколько кадров сообщение стоит в промежуточном узле. По умолчанию dur.hold */
  dwell?: number;
}

/**
 * Схема перебивки — очередь RabbitMQ: сообщение уходит консьюмеру, тот
 * подтверждает (ACK), сообщение из очереди исчезает, остальные сдвигаются.
 */
export interface QueueSpec {
  /** подписи сообщений в очереди слева направо */
  cells: string[];
  consumer: string;
  /** кадр: первое сообщение уходит к консьюмеру */
  deliverAt: number;
  /** кадр: консьюмер подтверждает — бейдж ACK */
  ackAt: number;
  /** кадр: сообщение удалено, очередь сдвигается */
  dropAt: number;
}

/**
 * Схема перебивки — лог Kafka: события остаются на месте, консьюмер держит
 * offset и может вернуться назад и перечитать. Показание OFFSET — число
 * прочитанных событий, оно всегда догоняет курсор, готовым не появляется.
 */
export interface LogSpec {
  /** сколько событий в логе */
  cells: number;
  /** кадр: консьюмер начинает читать с первого события */
  readAt: number;
  /** кадров на одно событие при чтении и повторе. По умолчанию dur.elem */
  step?: number;
  /** кадр: подпись RETENTION над логом */
  retentionAt?: number;
  /** кадр: показание OFFSET */
  offsetAt?: number;
  /** кадр: offset перематывается назад на событие rewindTo (номер с единицы) */
  rewindAt?: number;
  rewindTo?: number;
  /** кадр: чтение с rewindTo заново */
  replayAt?: number;
}

/**
 * Схема перебивки — клиент и сервер друг напротив друга, между ними две
 * полосы: запрос слева направо, ответ справа налево. Сообщение — ячейка,
 * летит по полосе `travel` кадров; узел, куда оно пришло, на блок залит.
 * `channel` — рамка вокруг полос с подписью (HTTP/2): постоянное соединение.
 * `modes` — плашка режима над схемой (UNARY, STREAMING…), сменяется по кадрам.
 */
export interface RpcMessage {
  /** кадр выхода */
  at: number;
  /** req — от клиента к серверу, res — обратно */
  dir: 'req' | 'res';
  /** подпись над ячейкой в полёте: ключ идемпотентности, id запроса */
  label?: string;
  /** потерялось на полпути: ячейка встаёт на середине полосы, там крестик */
  lost?: boolean;
}

/**
 * Журнал под сервером: что сервер у себя записал (списания, ключи).
 * Строка появляется на своём кадре; `hitAt` — сервер нашёл её снова,
 * строка на блок залита тоном перебивки.
 */
export interface RpcLedger {
  title: string;
  rows: {at: number; text: string; hitAt?: number}[];
}

export interface RpcSpec {
  client: string;
  server: string;
  /** подписи полос. По умолчанию REQUEST / RESPONSE */
  reqLabel?: string;
  resLabel?: string;
  /** подпись канала — рамка вокруг обеих полос */
  channel?: string;
  /** кадр: рамка канала появляется. По умолчанию 0 */
  channelAt?: number;
  modes?: {at: number; label: string}[];
  messages: RpcMessage[];
  /** кадров на перелёт. По умолчанию dur.beat */
  travel?: number;
  ledger?: RpcLedger;
  /** клиент ждёт ответа: залит тоном, под ним подпись с бегущими точками —
   *  до первого ответа, который до него дошёл */
  wait?: {at: number; label: string};
}

/**
 * Схема перебивки — документы и узлы. Документ: чип (имя файла, метод) и
 * моноширинные строки; пунктиром — живёт отдельно и необязателен, залитый —
 * бинарный блок. Узел — блок как в потоке, `lit` — залит тоном перебивки.
 * Элементы стоят по центру `x` (доля ширины) в ряду `row`, стрелки — по id.
 */
export interface DocItem {
  id: string;
  kind: 'doc' | 'node';
  /** узел — подпись; документ — чип над строками: имя файла или метод */
  label: string;
  /** центр по горизонтали, доля ширины схемы */
  x: number;
  /** ряд сверху вниз, с нуля */
  row: number;
  /** ширина, доля ширины схемы. По умолчанию 0.36 у документа, 0.28 у узла */
  w?: number;
  /** строки документа, моноширинные; не больше пяти */
  lines?: string[];
  /** пунктиром и muted: живёт отдельно, необязателен */
  dashed?: boolean;
  /** залит ink, текст paper: бинарный блок */
  solid?: boolean;
  /** узел залит тоном перебивки: только что появился */
  lit?: boolean;
  /** кадр появления */
  at: number;
}

export interface DocArrow {
  from: string;
  to: string;
  at: number;
}

export interface DocsSpec {
  items: DocItem[];
  arrows?: DocArrow[];
  /** рядов в схеме. По умолчанию 2 */
  rows?: number;
}

/**
 * Схема перебивки — веер запросов и хеджирование: клиент слева, справа
 * колонка серверов (сервисы, в которые ходит клиент, или инстансы одного
 * сервиса — тогда вокруг них рамка `frame` с подписью). Запрос — ячейка,
 * летит от клиента к серверу по стрелке, ответ — по ней же обратно. Сервер
 * с запросом внутри залит; сервер, который висит, — alarm в перебивке-проблеме
 * и приглушён в перебивке-ответе; отменённый запрос — крестик на стрелке.
 */
export interface RaceRequest {
  /** кадр выхода запроса от клиента */
  at: number;
  /** индекс сервера */
  to: number;
  /** кадр: сервер отвечает, ответ летит обратно `travel` кадров */
  replyAt?: number;
  /** кадр: сервер «висит» — залит alarm (tone alarm) или приглушён (tone accent) */
  hangAt?: number;
  /** кадр: запрос отменён — крестик на стрелке, сервер гаснет */
  cancelAt?: number;
}

export interface RaceSpec {
  client: string;
  servers: string[];
  /** рамка вокруг серверов с подписью — инстансы одного сервиса */
  frame?: string;
  /** кадр появления клиента; серверы — каскадом следом. По умолчанию 0 */
  at?: number;
  requests: RaceRequest[];
  /** кадр: клиент ждёт — залит тоном, пока не придёт следующий ответ */
  waitAt?: number;
  /** плашка над схемой (ДОЛЬШЕ P95, ЧЕРЕЗ 10 МС): появляется на кадре */
  badge?: {at: number; label: string};
  /** кадров на перелёт. По умолчанию dur.beat */
  travel?: number;
}

/** Подпись в зоне субтитров: кадры от начала перебивки. */
export interface CutCaption {
  at: number;
  until: number;
  text: string;
}

export interface CutSpec {
  kicker: string;
  badge: string;
  title: string;
  /** Montserrat 900 при 112 px берёт ~13 заглавных в строку, дальше — сюда. */
  titleSize?: number;
  /** accent и alarm в одном кадре не встречаются — тон задаётся на перебивку. */
  tone: 'accent' | 'alarm';
  /** схема — одна из: дорожки партиций, пулы потоков, поток по ярусам, очередь, лог, клиент-сервер, документы, веер запросов */
  lanes?: {total: number; steps: CutStep[]};
  pools?: PoolsSpec;
  flow?: FlowSpec;
  queue?: QueueSpec;
  log?: LogSpec;
  rpc?: RpcSpec;
  docs?: DocsSpec;
  race?: RaceSpec;
  /** `at` — кадр от начала перебивки, когда показание трогается с места. */
  meter?: MeterSpec & {at: number};
  sticker?: StickerSpec & {at: number};
  captions: CutCaption[];
}
