import type {MeterSpec, StickerSpec} from '../motion/types';

/**
 * Схема перебивки — партиции топика и консьюмеры на них.
 * Состояние задаётся шагами: что показано и в каком кадре это изменилось.
 * Дорожки и консьюмеры только добавляются, обратно не убираются.
 */
export interface CutStep {
  /** кадр от начала перебивки */
  at: number;
  /** сколько партиций показано */
  open: number;
  /** сообщений в очереди: одно число на все дорожки или по числу на каждую */
  cells: number | number[];
  /** сколько партиций читает свой консьюмер */
  consumers: number;
  /** консьюмеры, которым партиции не досталось, — стоят и ничего не делают */
  idle?: number;
  /** за сколько кадров меняется заполнение очередей. По умолчанию dur.block */
  over?: number;
}

/**
 * Схема перебивки — пулы потоков вызывающего сервиса и ресурсы, в которые
 * они ходят. Один пул = одна строка: слоты потоков, стрелка, ресурс.
 * Как и у дорожек, состояние только нарастает: пулы открываются, потоки
 * застревают, ресурсы зависают — обратно ничего не откатывается.
 */
export interface PoolStep {
  /** кадр от начала перебивки */
  at: number;
  /** сколько пулов показано */
  open: number;
  /** застрявших потоков в каждом пуле: ждут ответа, который не придёт */
  stuck: number[];
  /** работающих потоков в каждом пуле (accent, «происходит сейчас») */
  busy?: number[];
  /** индексы ресурсов, которые не отвечают */
  hung?: number[];
  /** вызывающий сервис лёг: свободных потоков не осталось */
  dead?: boolean;
  /** за сколько кадров застревают потоки этого шага. По умолчанию dur.block */
  over?: number;
}

export interface PoolsSpec {
  /** подпись вызывающего сервиса на рамке */
  caller: string;
  pools: {
    /** потоков в пуле; 4 в общем пуле читаются, 6 — уже нет */
    size: number;
    /** ресурс, в который ходит пул */
    target: string;
  }[];
  steps: PoolStep[];
}

/** Подпись в зоне субтитров: кадры от начала перебивки. */
export interface CutCaption {
  at: number;
  until: number;
  text: string;
}

export interface CutSpec {
  kicker: string;
  badge: string;
  title: string;
  /** Montserrat 900 при 112 px берёт ~13 заглавных в строку, дальше — сюда. */
  titleSize?: number;
  /** accent и alarm в одном кадре не встречаются — тон задаётся на перебивку. */
  tone: 'accent' | 'alarm';
  /** схема — одна из двух: дорожки партиций или пулы потоков */
  lanes?: {total: number; steps: CutStep[]};
  pools?: PoolsSpec;
  /** `at` — кадр от начала перебивки, когда показание трогается с места. */
  meter?: MeterSpec & {at: number};
  sticker?: StickerSpec & {at: number};
  captions: CutCaption[];
}
